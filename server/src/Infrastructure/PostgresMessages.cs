using KitchenTable.Application;
using KitchenTable.Domain;
using Npgsql;

namespace KitchenTable.Infrastructure;

public sealed class PostgresMessages(NpgsqlDataSource database) : IMessageStore
{
    public async Task Initialize(CancellationToken ct)
    {
        await using var command = database.CreateCommand("""
            CREATE TABLE IF NOT EXISTS messages (
                id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                sender uuid NOT NULL, token uuid NOT NULL, body text NOT NULL,
                sent_at timestamptz NOT NULL DEFAULT now(), UNIQUE(sender, token)
            );
            """);
        await command.ExecuteNonQueryAsync(ct);
    }

    public async Task<long> Append(DraftMessage message, CancellationToken ct)
    {
        await using var connection = await database.OpenConnectionAsync(ct);
        await using var transaction = await connection.BeginTransactionAsync(ct);
        // A history cursor must never pass an earlier, still-uncommitted message in this room.
        await using var roomLock = new NpgsqlCommand(
            "LOCK TABLE messages IN SHARE ROW EXCLUSIVE MODE", connection, transaction);
        await roomLock.ExecuteNonQueryAsync(ct);
        await using var command = new NpgsqlCommand("""
            INSERT INTO messages(sender, token, body) VALUES ($1, $2, $3)
            ON CONFLICT(sender, token) DO NOTHING RETURNING id
            """, connection, transaction);
        command.Parameters.AddWithValue(message.Sender);
        command.Parameters.AddWithValue(message.Token);
        command.Parameters.AddWithValue(message.Body);
        var id = (long?)await command.ExecuteScalarAsync(ct);
        if (id is null)
        {
            command.CommandText = "SELECT id FROM messages WHERE sender=$1 AND token=$2 AND body=$3";
            id = (long?)await command.ExecuteScalarAsync(ct)
                 ?? throw new MessageRuleException("Message token was already used for different text.");
        }
        await transaction.CommitAsync(ct);
        return id.Value;
    }

    public async Task<List<Message>> ReadAfter(long after, CancellationToken ct)
    {
        await using var command = database.CreateCommand("""
            SELECT id, sender, body, sent_at FROM messages
            WHERE id > $1 ORDER BY id LIMIT 200
            """);
        command.Parameters.AddWithValue(after);
        await using var rows = await command.ExecuteReaderAsync(ct);
        var messages = new List<Message>();
        while (await rows.ReadAsync(ct))
            messages.Add(new(rows.GetInt64(0), rows.GetGuid(1), rows.GetString(2), rows.GetDateTime(3)));
        return messages;
    }
}
